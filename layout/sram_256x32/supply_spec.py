#!/usr/bin/env python3
"""Emit the macro supply spec ``macro.supply.json`` consumed by ``klt erc`` (issue #229).

Every layer, label, via and tap definition is derived from the generator
constants (``generate.py`` and ``layout/bitcell/generate.py``), never
hand-copied, so "the stack matches the generator's constants" stays true by
construction: a layer renumbering in either generator changes this spec on its
next run, and ``test_macro.py::test_supply_spec_is_current`` (plus
``./layout/verify.sh`` step 11) fails until the spec is re-emitted.

What the spec declares, and why:

* **stackup** -- fabrication order from the gate: GatPoly (the gate role, with
  Activ as ``active_layer`` so gate area is ``poly ∩ diff``), then Metal1..Metal5.
  Activ is deliberately *not* a conductor role: diffusion is a device body, and
  a wire-model conductor there would short every transistor's source to its
  drain through the channel. Cont is declared as the GatPoly-Metal1 via (it
  bridges only where it overlaps both, so source/drain contacts bridge nothing
  -- diffusion is no role).
* **vias** -- the stack the supply rails actually use: Cont, Via1, Via2, Via3,
  Via4 (the generator draws no other via between these metals).
* **nets** -- VDD and VSS as ``kind: "supply"`` owning the roles only the rails
  draw (Metal4 lanes/straps and the Metal5 trunks; signal routing is Metal2/
  Metal3 and the pins are Metal2 squares). Owning the roles turns on the
  unlabelled-remainder measurement (``erc.unlabelled_conductor``), which is
  what sees a severed rail that the island count cannot. No ``islands`` count
  and no ``unlabelled_allowed_boxes`` are declared: the as-built report is
  expected to carry findings (the pin squares are not on the rails yet, #108)
  and declaring either to quiet it is forbidden by issue #229.
* **ties** -- both body-tie classes the generators draw: the n-well tie to VDD
  and the p-substrate tie to VSS. The **tap is the Cont square**, not the tie
  Activ strip: ``connect_to`` wires a tap to its role by plan-view overlap
  (``l2n.connect``), and the bitcell's full-height BL/BLB Metal1 stripes cross
  the full-width tie strips without a contact -- an Activ-strip tap would
  weld VDD and VSS into one tie-graph net as a false ``erc.supply_short``
  (measured on the bitcell fixture; the friction is filed on klayout-tools).
  The Cont of the tie is overlapped by exactly its own supply riser/pad, so
  the tie graph stays honest. Polarity: the n-well tie contact is Cont inside
  NWell with no pSD over it (pSD covers the PMOS source/drain instead) and
  not on GatPoly (that is a gate contact); the p-substrate tie contact is
  Cont under pSD on the substrate, which is the macro extent minus NWell
  (``well_complement_of``; SG13G2's p bulk draws no layer of its own).

Run from the repo root (or anywhere; paths resolve next to this file)::

    uv run --with klayout python3 layout/sram_256x32/supply_spec.py
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import generate as g  # noqa: E402  (rails_check.py uses the same import)

SPEC_PATH = os.path.join(HERE, "macro.supply.json")


def _ld(lp: tuple[int, int]) -> str:
    return f"{lp[0]}/{lp[1]}"


def spec() -> dict:
    """The supply spec as a plain dict (also imported by the tests)."""
    bc = g.bc
    return {
        "_comment": [
            "Supply spec of layout/sram_256x32/macro.gds for klt erc (issue #229).",
            "Generated by supply_spec.py from the constants of generate.py and",
            "layout/bitcell/generate.py; do not edit macro.supply.json by hand.",
            "Metal4/Metal5 are rail-only (signal routing is Metal2/Metal3, pins are",
            "Metal2), so both supplies own them outright for the unlabelled-remainder",
            "measurement. No islands count and no allowed boxes are declared: the",
            "as-built findings (pin squares off the rails, #108) are the honest result.",
        ],
        "stackup": [
            {
                "name": "gatpoly",
                "layer": _ld(bc.L_GATPOLY),
                "role": "gate",
                "active_layer": _ld(bc.L_ACTIV),
                "label_layer": _ld(bc.L_GATPOLY_LBL),
            },
            {"name": "metal1", "layer": _ld(bc.L_METAL1), "label_layer": _ld(bc.L_METAL1_LBL)},
            {"name": "metal2", "layer": _ld(g.L_METAL2), "label_layer": _ld(g.L_METAL2_LBL)},
            {"name": "metal3", "layer": _ld(g.L_METAL3)},
            {"name": "metal4", "layer": _ld(g.L_METAL4)},
            {"name": "metal5", "layer": _ld(g.L_METAL5), "label_layer": _ld(g.L_METAL5_LBL)},
        ],
        "vias": [
            {"name": "cont", "layer": _ld(bc.L_CONT), "between": ["gatpoly", "metal1"]},
            {"name": "via1", "layer": _ld(g.L_VIA1), "between": ["metal1", "metal2"]},
            {"name": "via2", "layer": _ld(g.L_VIA2), "between": ["metal2", "metal3"]},
            {"name": "via3", "layer": _ld(g.L_VIA3), "between": ["metal3", "metal4"]},
            {"name": "via4", "layer": _ld(g.L_VIA4), "between": ["metal4", "metal5"]},
        ],
        "nets": [
            {"name": net, "kind": "supply", "roles": ["metal4", "metal5"]}
            for net in g.SUPPLY_NETS
        ],
        "ties": [
            {
                "name": "nwell_vdd",
                "well_layer": _ld(bc.L_NWELL),
                "tap_layer": _ld(bc.L_CONT),
                "tap_requires": [_ld(bc.L_NWELL), _ld(bc.L_ACTIV)],
                "tap_excludes": [_ld(bc.L_PSD), _ld(bc.L_GATPOLY)],
                "connect_to": "metal1",
                "net": "VDD",
            },
            {
                "name": "psub_vss",
                "well_layer": None,
                "well_complement_of": [_ld(bc.L_NWELL)],
                "tap_layer": _ld(bc.L_CONT),
                "tap_requires": [_ld(bc.L_PSD), _ld(bc.L_ACTIV)],
                "tap_excludes": [_ld(bc.L_GATPOLY)],
                "connect_to": "metal1",
                "net": "VSS",
            },
        ],
    }


def main() -> None:
    with open(SPEC_PATH, "w") as f:
        json.dump(spec(), f, indent=2)
        f.write("\n")
    print(f"wrote {SPEC_PATH}")


if __name__ == "__main__":
    main()
